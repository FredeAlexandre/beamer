"""Generates tests/vectors/aead.txt with PyNaCl (libsodium), the AEAD the Phase 1 prototype used.

    uv run --python 3.13 --with pynacl native/audio/tests/gen_vectors.py

Each line: key nonce aad plaintext ciphertext||tag, hex. Seeded, so the file is reproducible.
The RFC 8439 §2.8.2 vector is checked here too (and again in engine_tests).
"""
from __future__ import annotations

import random
import struct
from pathlib import Path

from nacl import bindings as nb

RFC_KEY = bytes(range(0x80, 0xA0))
RFC_NONCE = bytes.fromhex("070000004041424344454647")
RFC_AAD = bytes.fromhex("50515253c0c1c2c3c4c5c6c7")
RFC_PT = (b"Ladies and Gentlemen of the class of '99: If I could offer you only one tip for "
          b"the future, sunscreen would be it.")
RFC_CT = bytes.fromhex(
    "d31a8d34648e60db7b86afbc53ef7ec2a4aded51296e08fea9e2b5a736ee62d63dbea45e8ca9671282fafb69da92728b"
    "1a71de0a9e060b2905d6a5b67ecd3b3692ddbd7f2d778b8c9803aee328091b58fab324e4fad675945585808b4831d7bc"
    "3ff4def08e4b7a9de576d26586cec64b6116")
RFC_TAG = bytes.fromhex("1ae10b594f09e26a7e902ecbd0600691")


def main() -> None:
    out = nb.crypto_aead_chacha20poly1305_ietf_encrypt(RFC_PT, RFC_AAD, RFC_NONCE, RFC_KEY)
    assert out == RFC_CT + RFC_TAG, "RFC 8439 vector mismatch"
    rng = random.Random(8439)
    lines = ["# key nonce aad plaintext ciphertext||tag (hex); generated by gen_vectors.py with PyNaCl"]
    sizes = [0, 1, 15, 16, 17, 38, 63, 64, 65, 120, 255, 1000, 1400]
    for i, n in enumerate(sizes * 2):
        key = rng.randbytes(32)
        stream = rng.getrandbits(31) or 1
        seq = rng.getrandbits(40) + 1
        dir_stream = stream | (0x80000000 if i % 2 else 0)
        nonce = struct.pack("!IQ", dir_stream, seq)
        # a packet header as associated data (§4.1): version 1, ptype media, fec, opus
        aad = struct.pack("!BBBBIQIHBB", 1, 1, 1, 1, stream, seq, rng.getrandbits(32), 480, 1, 0)
        if i % 5 == 4:
            aad = rng.randbytes(rng.randrange(0, 40))  # arbitrary AAD lengths too
        pt = rng.randbytes(n)
        ct = nb.crypto_aead_chacha20poly1305_ietf_encrypt(pt, aad, nonce, key)
        lines.append(" ".join(x.hex() or "-" for x in (key, nonce, aad, pt, ct)))
    path = Path(__file__).with_name("vectors") / "aead.txt"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path} ({len(lines) - 1} vectors)")


if __name__ == "__main__":
    main()
